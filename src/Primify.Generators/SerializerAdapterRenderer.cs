namespace Primify.Generators;

using System.Text;

/// <summary>
/// Renders the shared serializer adapter sources emitted once per consumer compilation, only when the
/// consumer references the matching serializer package. Keeping these out of the runtime package is what
/// lets Primify ship without a LiteDB or Newtonsoft.Json dependency.
/// </summary>
internal static class SerializerAdapterRenderer
{
    /// <summary>
    /// Renders the LiteDB registration source: a <c>LiteDbRegistration.Register(BsonMapper)</c> method with
    /// one inline <c>RegisterType</c> call per wrapper, plus a module initializer that applies it to
    /// <c>BsonMapper.Global</c>. Each mapping converts the wrapper to a BSON type LiteDB stores natively on
    /// write and rebuilds it through <c>From</c> on read. The class is <c>internal</c> on purpose: every
    /// consumer assembly emits its own copy, and <c>internal</c> keeps those copies from clashing (CS0433) in
    /// downstream assemblies that reference two Primify wrapper libraries.
    /// </summary>
    public static string RenderLiteDbRegistration(PrimifyModel[] models)
    {
        var needsDtoDocument = models.Any(static model => model.LiteDbStorage == LiteDbStorageKind.DateTimeOffsetDocument);
        var needsUtcStorage = models.Any(static model => model.LiteDbStorage == LiteDbStorageKind.UtcDateTime);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace Primify.Converters");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Registers LiteDB mappings for every Primify wrapper in this assembly. Generated only when the");
        sb.AppendLine("    /// consumer references LiteDB; values are converted to BSON types LiteDB stores natively on write");
        sb.AppendLine("    /// and rebuilt through <c>From</c> on read, so validation runs during deserialization. The class is");
        sb.AppendLine("    /// internal so that assemblies emitting their own copy never clash in a downstream assembly.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    internal static class LiteDbRegistration");
        sb.AppendLine("    {");
        sb.AppendLine("        /// <summary>Registers the built-in mapping of every wrapper in this assembly on the given mapper.</summary>");
        sb.AppendLine("        /// <param name=\"mapper\">The mapper to update, for example <c>BsonMapper.Global</c>. Registering again replaces.</param>");
        sb.AppendLine("        public static void Register(global::LiteDB.BsonMapper mapper)");
        sb.AppendLine("        {");

        for (var index = 0; index < models.Length; index++)
        {
            var model = models[index];
            var (writeValue, _, _) = GetLiteDbExpressions(model);
            sb.AppendLine($"            mapper.RegisterType<{model.FullyQualifiedTypeName}>(");
            sb.AppendLine($"                serialize: {writeValue},");
            sb.AppendLine($"                deserialize: bson => {model.FullyQualifiedTypeName}.From(Parse{index}(bson)));");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        [System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        internal static void RegisterOnGlobalMapper() => Register(global::LiteDB.BsonMapper.Global);");
        sb.AppendLine();

        AppendReadHelpers(sb, needsUtcStorage);

        if (needsDtoDocument)
        {
            AppendDateTimeOffsetHelpers(sb);
        }

        for (var index = 0; index < models.Length; index++)
        {
            var model = models[index];
            var (_, parseBody, parseType) = GetLiteDbExpressions(model);
            var fq = model.FullyQualifiedTypeName;
            sb.AppendLine();
            sb.AppendLine($"        private static {parseType} Parse{index}(global::LiteDB.BsonValue bson)");
            sb.AppendLine("        {");
            sb.AppendLine("            try");
            sb.AppendLine("            {");
            sb.AppendLine(parseBody);
            sb.AppendLine("            }");
            sb.AppendLine("            catch (global::System.Exception ex) when (ex is not global::System.FormatException)");
            sb.AppendLine("            {");
            sb.AppendLine($"                throw MalformedValue<{fq}>($\"the stored BSON value cannot be converted ({{ex.Message}}).\");");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Builds the write lambda and the parse-body fragment for one wrapper. The write lambda converts the
    /// wrapper to a BSON value; the parse body converts a BSON value back to the wrapped (or underlying
    /// nullable) type. A wrapper around <c>Nullable&lt;T&gt;</c> stores a <c>{ "Value": bson }</c> document,
    /// because LiteDB cannot read a BSON <c>Null</c> back into a registered value-type custom mapping
    /// (the engine throws inside <c>DeserializeObject</c> before calling the mapping). The parse body is
    /// wrapped in a try/catch by the caller, which turns any failure — including the
    /// <c>OverflowException</c> from a checked cast or the <c>ArgumentOutOfRangeException</c> from an
    /// out-of-range <c>TimeOnly</c> — into a described <see cref="FormatException"/>.
    /// </summary>
    private static (string Write, string ParseBody, string ParseType) GetLiteDbExpressions(PrimifyModel model)
    {
        var fq = model.FullyQualifiedTypeName;
        var wrapsNullable = model.WrapsNullableValueType;
        var wv = wrapsNullable ? "wrapper.Value.GetValueOrDefault()" : "wrapper.Value";
        var ut = model.UnderlyingWrappedType;
        var parseType = model.WrappedType!;

        string writeValue = model.LiteDbStorage switch
        {
            LiteDbStorageKind.String =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Boolean =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Int32 =>
                $"new global::LiteDB.BsonValue((int){wv})",
            LiteDbStorageKind.Int64 =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.UInt32 =>
                $"new global::LiteDB.BsonValue((long){wv})",
            LiteDbStorageKind.UInt64 =>
                $"new global::LiteDB.BsonValue(checked((long){wv}))",
            LiteDbStorageKind.Double =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Single =>
                $"new global::LiteDB.BsonValue((double){wv})",
            LiteDbStorageKind.Half =>
                $"new global::LiteDB.BsonValue((double){wv})",
            LiteDbStorageKind.Decimal =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Guid =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.UtcDateTime =>
                $"new global::LiteDB.BsonValue(EnsureUtc({wv}))",
            LiteDbStorageKind.TimeSpanTicks =>
                $"new global::LiteDB.BsonValue({wv}.Ticks)",
            LiteDbStorageKind.TimeOnlyTicks =>
                $"new global::LiteDB.BsonValue({wv}.Ticks)",
            LiteDbStorageKind.DateOnlyUtcMidnight =>
                $"new global::LiteDB.BsonValue(global::System.DateTime.SpecifyKind({wv}.ToDateTime(global::System.TimeOnly.MinValue), global::System.DateTimeKind.Utc))",
            LiteDbStorageKind.DateTimeOffsetDocument =>
                $"new global::LiteDB.BsonDocument {{ [\"UtcTicks\"] = new global::LiteDB.BsonValue({wv}.UtcTicks), [\"OffsetTicks\"] = new global::LiteDB.BsonValue({wv}.Offset.Ticks) }}",
            _ => $"new global::LiteDB.BsonValue({wv})"
        };

        var write = wrapsNullable
            ? $"wrapper => new global::LiteDB.BsonDocument {{ [\"Value\"] = wrapper.Value.HasValue ? {writeValue} : global::LiteDB.BsonValue.Null }}"
            : $"wrapper => {writeValue}";

        string Body(string b) => model.LiteDbStorage switch
        {
            LiteDbStorageKind.String =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.String);\n                return {b}.AsString;",
            LiteDbStorageKind.Boolean =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Boolean);\n                return {b}.AsBoolean;",
            LiteDbStorageKind.Int32 =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);\n                return checked(({ut}){b}.AsInt64);",
            LiteDbStorageKind.Int64 =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);\n                return checked((long){b}.AsInt64);",
            LiteDbStorageKind.UInt32 =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);\n                return checked((uint){b}.AsInt64);",
            LiteDbStorageKind.UInt64 =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int64);\n                return checked((ulong){b}.AsInt64);",
            LiteDbStorageKind.Double =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Double);\n                return {b}.AsDouble;",
            LiteDbStorageKind.Single =>
                "Expect<" + fq + ">(" + b + ", global::LiteDB.BsonType.Double);\n" +
                "                var single = " + b + ".AsDouble;\n" +
                "                if (double.IsFinite(single) && global::System.Math.Abs(single) > global::System.Single.MaxValue)\n" +
                "                {\n" +
                "                    throw MalformedValue<" + fq + ">(\"the stored double is out of range for System.Single.\");\n" +
                "                }\n" +
                "                return (float)single;",
            LiteDbStorageKind.Half =>
                "Expect<" + fq + ">(" + b + ", global::LiteDB.BsonType.Double);\n" +
                "                var half = " + b + ".AsDouble;\n" +
                "                if (double.IsFinite(half) && global::System.Math.Abs(half) > (double)global::System.Half.MaxValue)\n" +
                "                {\n" +
                "                    throw MalformedValue<" + fq + ">(\"the stored double is out of range for System.Half.\");\n" +
                "                }\n" +
                "                return (global::System.Half)half;",
            LiteDbStorageKind.Decimal =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Decimal);\n                return {b}.AsDecimal;",
            LiteDbStorageKind.Guid =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Guid);\n                return {b}.AsGuid;",
            LiteDbStorageKind.UtcDateTime =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.DateTime);\n                return {b}.AsDateTime.ToUniversalTime();",
            LiteDbStorageKind.TimeSpanTicks =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);\n                return new global::System.TimeSpan({b}.AsInt64);",
            LiteDbStorageKind.TimeOnlyTicks =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);\n                return new global::System.TimeOnly({b}.AsInt64);",
            LiteDbStorageKind.DateOnlyUtcMidnight =>
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.DateTime);\n                return global::System.DateOnly.FromDateTime({b}.AsDateTime.ToUniversalTime());",
            LiteDbStorageKind.DateTimeOffsetDocument =>
                $"return ReadDateTimeOffsetDocument<{fq}>({b});",
            _ => $"Expect<{fq}>({b}, global::LiteDB.BsonType.String);\n                return {b}.AsString;"
        };

        var parseBody = wrapsNullable
            ? "if (bson is null || bson is not global::LiteDB.BsonDocument document)\n" +
              "                {\n" +
              "                    throw MalformedValue<" + fq + ">(bson is null\n" +
              "                        ? \"expected a '{ Value }' document but found null.\"\n" +
              "                        : $\"expected a '{{ Value }}' document but found {bson.Type}.\");\n" +
              "                }\n" +
              "                if (!document.TryGetValue(\"Value\", out var value))\n" +
              "                {\n" +
              $"                    throw MalformedValue<{fq}>(\"the document is missing the 'Value' field.\");\n" +
              "                }\n" +
              "                if (value.IsNull)\n" +
              "                {\n" +
              "                    return default;\n" +
              "                }\n" +
              Body("value")
            : Body("bson");

        return (write, parseBody, parseType);
    }

    private static void AppendReadHelpers(StringBuilder sb, bool needsUtcStorage)
    {
        sb.AppendLine("        private static void Expect<TWrapper>(global::LiteDB.BsonValue bson, params global::LiteDB.BsonType[] expected)");
        sb.AppendLine("        {");
        sb.AppendLine("            foreach (var type in expected)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (bson.Type == type)");
        sb.AppendLine("                {");
        sb.AppendLine("                    return;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            throw new global::System.FormatException($\"Primify cannot read the stored BSON value for '{typeof(TWrapper).Name}': expected {string.Join(\" or \", expected)} but found {bson.Type}.\");");
        sb.AppendLine("        }");

        if (needsUtcStorage)
        {
            sb.AppendLine();
            sb.AppendLine("        // Treat an Unspecified-kind DateTime as UTC instead of local time: the ticks are stored as");
            sb.AppendLine("        // written, and reading them back as UTC preserves the wall clock. A Local DateTime is converted.");
            sb.AppendLine("        private static global::System.DateTime EnsureUtc(global::System.DateTime value) =>");
            sb.AppendLine("            value.Kind == global::System.DateTimeKind.Unspecified");
            sb.AppendLine("                ? global::System.DateTime.SpecifyKind(value, global::System.DateTimeKind.Utc)");
            sb.AppendLine("                : value.ToUniversalTime();");
        }

        sb.AppendLine();
        sb.AppendLine("        private static global::System.FormatException MalformedValue<TWrapper>(string reason) =>");
        sb.AppendLine("            new($\"Primify cannot read the stored BSON value for '{typeof(TWrapper).Name}': {reason}\");");
    }

    private static void AppendDateTimeOffsetHelpers(StringBuilder sb)
    {
        sb.AppendLine();
        sb.AppendLine("        // LiteDB has no native DateTimeOffset type and its BSON DateTime is millisecond-precision, so both");
        sb.AppendLine("        // components are stored as raw tick counts: the instant stays exact to the tick and the offset survives.");
        sb.AppendLine("        private static global::System.DateTimeOffset ReadDateTimeOffsetDocument<TWrapper>(global::LiteDB.BsonValue bson)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (bson is not global::LiteDB.BsonDocument document)");
        sb.AppendLine("            {");
        sb.AppendLine("                throw MalformedValue<TWrapper>($\"expected a '{{ UtcTicks, OffsetTicks }}' document but found {bson.Type}.\");");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            if (!TryReadTicks(document, \"UtcTicks\", out var utcTicks) ||");
        sb.AppendLine("                !TryReadTicks(document, \"OffsetTicks\", out var offsetTicks))");
        sb.AppendLine("            {");
        sb.AppendLine("                throw MalformedValue<TWrapper>(");
        sb.AppendLine("                    \"the document is missing integer 'UtcTicks' and 'OffsetTicks' fields.\");");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            try");
        sb.AppendLine("            {");
        sb.AppendLine("                return new global::System.DateTimeOffset(utcTicks, global::System.TimeSpan.Zero)");
        sb.AppendLine("                    .ToOffset(global::System.TimeSpan.FromTicks(offsetTicks));");
        sb.AppendLine("            }");
        sb.AppendLine("            catch (global::System.ArgumentException exception)");
        sb.AppendLine("            {");
        sb.AppendLine("                throw MalformedValue<TWrapper>($\"the stored ticks are not a valid instant ({exception.Message}).\");");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        private static bool TryReadTicks(global::LiteDB.BsonDocument document, string field, out long ticks)");
        sb.AppendLine("        {");
        sb.AppendLine("            ticks = 0;");
        sb.AppendLine();
        sb.AppendLine("            if (!document.TryGetValue(field, out var value) || value.Type != global::LiteDB.BsonType.Int64)");
        sb.AppendLine("            {");
        sb.AppendLine("                return false;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            ticks = value.AsInt64;");
        sb.AppendLine("            return true;");
        sb.AppendLine("        }");
    }

    /// <summary>
    /// Renders the Newtonsoft.Json converter emitted into the consumer compilation when Newtonsoft.Json is
    /// referenced. The BSON branches are included only when Newtonsoft.Json.Bson is referenced as well.
    /// </summary>
    public static string RenderNewtonsoftConverter(bool bsonAvailable) =>
        bsonAvailable ? NewtonsoftBsonConverterSource : NewtonsoftJsonConverterSource;

    private const string SharedConverterMembers = """

            private static void WriteDateTimeOffsetObject(global::Newtonsoft.Json.JsonWriter writer, DateTimeOffset value)
            {
                writer.WriteStartObject();
                writer.WritePropertyName("UtcTicks");
                writer.WriteValue(value.UtcTicks);
                writer.WritePropertyName("OffsetTicks");
                writer.WriteValue(value.Offset.Ticks);
                writer.WriteEndObject();
            }

            private static DateTimeOffset ReadDateTimeOffsetObject(global::Newtonsoft.Json.JsonReader reader)
            {
                if (!reader.Read() ||
                    reader.TokenType != global::Newtonsoft.Json.JsonToken.PropertyName ||
                    !string.Equals(reader.Value as string, "UtcTicks", StringComparison.Ordinal) ||
                    !reader.Read() ||
                    reader.TokenType != global::Newtonsoft.Json.JsonToken.Integer)
                {
                    throw new global::Newtonsoft.Json.JsonSerializationException("A DateTimeOffset JSON object must start with UtcTicks.");
                }

                var utcTicks = Convert.ToInt64(reader.Value, System.Globalization.CultureInfo.InvariantCulture);

                if (!reader.Read() ||
                    reader.TokenType != global::Newtonsoft.Json.JsonToken.PropertyName ||
                    !string.Equals(reader.Value as string, "OffsetTicks", StringComparison.Ordinal) ||
                    !reader.Read() ||
                    reader.TokenType != global::Newtonsoft.Json.JsonToken.Integer)
                {
                    throw new global::Newtonsoft.Json.JsonSerializationException("A DateTimeOffset JSON object must contain OffsetTicks.");
                }

                var offsetTicks = Convert.ToInt64(reader.Value, System.Globalization.CultureInfo.InvariantCulture);

                if (!reader.Read() || reader.TokenType != global::Newtonsoft.Json.JsonToken.EndObject)
                {
                    throw new global::Newtonsoft.Json.JsonSerializationException("A DateTimeOffset JSON object must end after OffsetTicks.");
                }

                try
                {
                    return new DateTimeOffset(utcTicks, TimeSpan.Zero)
                        .ToOffset(TimeSpan.FromTicks(offsetTicks));
                }
                catch (ArgumentException exception)
                {
                    throw new global::Newtonsoft.Json.JsonSerializationException("The DateTimeOffset JSON object contains invalid ticks.", exception);
                }
            }
        """;

    private const string NewtonsoftJsonConverterSource = """
        // <auto-generated/>
        #nullable enable

        using System;

        namespace Primify.Converters;

        /// <summary>
        /// A reflection-free JSON converter for Primify wrapper types using Newtonsoft.Json, generated only when
        /// the consumer references Newtonsoft.Json. The generator attaches it to every wrapper via
        /// <c>[JsonConverter(typeof(NewtonsoftJsonConverter&lt;TWrapper,TValue&gt;))]</c>.
        /// </summary>
        /// <remarks>
        /// Reads deserialize the inner value first, then rebuild the wrapper through
        /// <see cref="IPrimify{TSelf, TValue}.From(TValue)"/>, so validation runs during deserialization.
        /// DateTimeOffset values use { "UtcTicks": ..., "OffsetTicks": ... } so the original offset survives
        /// Json.NET's date tokenization.
        /// </remarks>
        internal sealed class NewtonsoftJsonConverter<TWrapper, TValue> : global::Newtonsoft.Json.JsonConverter
            where TWrapper : IPrimify<TWrapper, TValue>
        {
            /// <summary>Accepts only the exact wrapper type, so the converter is never reused for a related type.</summary>
            public override bool CanConvert(Type objectType) => objectType == typeof(TWrapper);

            /// <summary>Writes the bare primitive, or the tick object for DateTimeOffset, keeping payloads flat.</summary>
            public override void WriteJson(global::Newtonsoft.Json.JsonWriter writer, object? value, global::Newtonsoft.Json.JsonSerializer serializer)
            {
                if (value is null)
                {
                    writer.WriteNull();
                    return;
                }

                var wrapper = (TWrapper)value;
                var innerValue = (object)wrapper.Value!;

                if (innerValue is DateTimeOffset dateTimeOffset)
                {
                    WriteDateTimeOffsetObject(writer, dateTimeOffset);
                }
                else
                {
                    serializer.Serialize(writer, innerValue);
                }
            }

            /// <summary>Reads a primitive or a DateTimeOffset tick object and returns a validated wrapper.</summary>
            public override object? ReadJson(global::Newtonsoft.Json.JsonReader reader, Type objectType, object? existingValue, global::Newtonsoft.Json.JsonSerializer serializer)
            {
                if (reader.TokenType == global::Newtonsoft.Json.JsonToken.Null)
                {
                    return null;
                }

                object? rawValue;

                if (reader.TokenType == global::Newtonsoft.Json.JsonToken.StartObject)
                {
                    if (typeof(TValue) == typeof(DateTimeOffset) && reader is global::Newtonsoft.Json.JsonTextReader)
                    {
                        rawValue = ReadDateTimeOffsetObject(reader);
                    }
                    else
                    {
                        throw new global::Newtonsoft.Json.JsonSerializationException("A Primify wrapper must be a primitive JSON value.");
                    }
                }
                else
                {
                    rawValue = serializer.Deserialize<TValue>(reader);
                }

                if (rawValue is null)
                {
                    throw new global::Newtonsoft.Json.JsonSerializationException($"The JSON payload does not contain a value for {typeof(TValue).Name}.");
                }

                return TWrapper.From((TValue)rawValue);
            }
        """ + SharedConverterMembers + """

        }
        """;

    private const string NewtonsoftBsonConverterSource = """
        // <auto-generated/>
        #nullable enable

        using System;

        namespace Primify.Converters;

        /// <summary>
        /// A reflection-free JSON + BSON converter for Primify wrapper types using Newtonsoft.Json, generated only
        /// when the consumer references Newtonsoft.Json and Newtonsoft.Json.Bson. The generator attaches it to
        /// every wrapper via <c>[JsonConverter(typeof(NewtonsoftJsonConverter&lt;TWrapper,TValue&gt;))]</c>.
        /// </summary>
        /// <remarks>
        /// Standard JSON payloads carry the bare primitive. DateTimeOffset values use
        /// { "UtcTicks": ..., "OffsetTicks": ... } so the original offset survives Json.NET's date tokenization.
        /// When writing to a <c>global::Newtonsoft.Json.Bson.BsonDataWriter</c>, the value is wrapped as { "Value": ... }; DateTimeOffset
        /// uses the same tick object inside that field. Deserialization rebuilds the wrapper through
        /// <see cref="IPrimify{TSelf, TValue}.From(TValue)"/>, so invalid payloads throw the wrapper's validation
        /// exception instead of yielding an unvalidated instance.
        /// </remarks>
        internal sealed class NewtonsoftJsonConverter<TWrapper, TValue> : global::Newtonsoft.Json.JsonConverter
            where TWrapper : IPrimify<TWrapper, TValue>
        {
            /// <summary>Accepts only the exact wrapper type, so the converter is never reused for a related type.</summary>
            public override bool CanConvert(Type objectType) => objectType == typeof(TWrapper);

            /// <summary>Writes the bare primitive, or a { "Value": ... } object when writing through a <c>global::Newtonsoft.Json.Bson.BsonDataWriter</c>.</summary>
            public override void WriteJson(global::Newtonsoft.Json.JsonWriter writer, object? value, global::Newtonsoft.Json.JsonSerializer serializer)
            {
                if (value is null)
                {
                    writer.WriteNull();
                    return;
                }

                var wrapper = (TWrapper)value;
                var innerValue = (object)wrapper.Value!;

                if (innerValue is DateTimeOffset dateTimeOffset && writer is not global::Newtonsoft.Json.Bson.BsonDataWriter)
                {
                    WriteDateTimeOffsetObject(writer, dateTimeOffset);
                }
                else if (writer is global::Newtonsoft.Json.Bson.BsonDataWriter)
                {
                    writer.WriteStartObject();
                    writer.WritePropertyName("Value");
                    if (innerValue is DateTimeOffset dto)
                    {
                        WriteDateTimeOffsetObject(writer, dto);
                    }
                    else
                    {
                        serializer.Serialize(writer, innerValue);
                    }

                    writer.WriteEndObject();
                }
                else
                {
                    serializer.Serialize(writer, innerValue);
                }
            }

            /// <summary>Reads a primitive, a DateTimeOffset tick object, or a BSON { "Value": ... } shape and returns a validated wrapper.</summary>
            public override object? ReadJson(global::Newtonsoft.Json.JsonReader reader, Type objectType, object? existingValue, global::Newtonsoft.Json.JsonSerializer serializer)
            {
                if (reader.TokenType == global::Newtonsoft.Json.JsonToken.Null)
                {
                    return null;
                }

                // global::Newtonsoft.Json.Bson.BsonDataReader tokenizes dates into local time before the converter sees them, so read the
                // tick object as UTC and restore the stored offset afterwards.
                if (reader is global::Newtonsoft.Json.Bson.BsonDataReader bsonReader && typeof(TValue) == typeof(DateTimeOffset))
                {
                    var originalKind = bsonReader.DateTimeKindHandling;
                    try
                    {
                        bsonReader.DateTimeKindHandling = DateTimeKind.Utc;
                        return ReadAndWrapValue(reader, serializer);
                    }
                    finally
                    {
                        bsonReader.DateTimeKindHandling = originalKind;
                    }
                }

                return ReadAndWrapValue(reader, serializer);
            }

            private object? ReadAndWrapValue(global::Newtonsoft.Json.JsonReader reader, global::Newtonsoft.Json.JsonSerializer serializer)
            {
                object? rawValue;

                if (reader.TokenType == global::Newtonsoft.Json.JsonToken.StartObject)
                {
                    if (typeof(TValue) == typeof(DateTimeOffset) && reader is global::Newtonsoft.Json.JsonTextReader)
                    {
                        rawValue = ReadDateTimeOffsetObject(reader);
                    }
                    else if (reader is not global::Newtonsoft.Json.Bson.BsonDataReader)
                    {
                        throw new global::Newtonsoft.Json.JsonSerializationException("A Primify wrapper must be a primitive JSON value.");
                    }
                    else
                    {
                        if (!reader.Read() ||
                            reader.TokenType != global::Newtonsoft.Json.JsonToken.PropertyName ||
                            !string.Equals(reader.Value as string, "Value", StringComparison.Ordinal))
                        {
                            throw new global::Newtonsoft.Json.JsonSerializationException("The BSON wrapper object must contain a Value property.");
                        }

                        if (!reader.Read())
                        {
