namespace Primify.Generators;

using System.Collections.Generic;

/// <summary>
/// Renders the shared serializer adapter sources emitted once per consumer compilation, only when the
/// consumer references the matching serializer package. Keeping these out of the runtime package is what
/// lets Primify ship without a LiteDB or Newtonsoft.Json dependency.
/// </summary>
/// <remarks>
/// Everything emitted into the consumer assembly is <c>global::</c>-qualified and the adapter files
/// carry no <c>using</c> directives, so they bind no matter what the consuming project declares.
/// </remarks>
internal static class SerializerAdapterRenderer
{
    /// <summary>
    /// Renders the LiteDB registration source: a <c>LiteDbRegistration.Register(BsonMapper)</c> method with
    /// one inline <c>RegisterType</c> call per wrapper, plus a module initializer that applies it to
    /// <c>BsonMapper.Global</c>. Each mapping converts the wrapper to a BSON type LiteDB stores natively on
    /// write and rebuilds it through <c>From</c> on read. The class is <c>internal</c> on purpose: every
    /// consumer assembly emits its own copy, and <c>internal</c> keeps those copies from clashing (CS0433) in
    /// downstream assemblies that reference two Primify wrapper libraries.
    /// </summary>
    public static string RenderLiteDbRegistration(PrimifyModel[] models)
    {
        var needsDtoDocument = models.Any(static model => model.LiteDbStorage == LiteDbStorageKind.DateTimeOffsetDocument);
        var needsUtcStorage = models.Any(static model => model.LiteDbStorage == LiteDbStorageKind.UtcDateTime);
        var writer = new SourceWriter();
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.BlankLine();
        writer.WriteLine("namespace Primify.Converters");
        writer.OpenBrace();
        writer.WriteLine("/// <summary>");
        writer.WriteLine("/// Registers LiteDB mappings for every Primify wrapper in this assembly. Generated only when the");
        writer.WriteLine("/// consumer references LiteDB; values are converted to BSON types LiteDB stores natively on write");
        writer.WriteLine("/// and rebuilt through <c>From</c> on read, so validation runs during deserialization. The class is");
        writer.WriteLine("/// internal so that assemblies emitting their own copy never clash in a downstream assembly.");
        writer.WriteLine("/// </summary>");
        writer.WriteLine("internal static class LiteDbRegistration");
        writer.OpenBrace();
        writer.WriteLine("/// <summary>Registers the built-in mapping of every wrapper in this assembly on the given mapper.</summary>");
        writer.WriteLine("/// <param name=\"mapper\">The mapper to update, for example <c>BsonMapper.Global</c>. Registering again replaces.</param>");
        writer.WriteLine("public static void Register(global::LiteDB.BsonMapper mapper)");
        writer.OpenBrace();

        for (var index = 0; index < models.Length; index++)
        {
            var model = models[index];
            var (writeValue, _, _) = GetLiteDbExpressions(model);
            writer.WriteLine($"mapper.RegisterType<{model.FullyQualifiedTypeName}>(");
            writer.PushIndent();
            writer.WriteLine($"serialize: {writeValue},");
            writer.WriteLine($"deserialize: bson => {model.FullyQualifiedTypeName}.From(Parse{index}(bson)));");
            writer.PopIndent();
        }

        writer.CloseBrace();
        writer.BlankLine();
        writer.WriteLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        writer.WriteLine("internal static void RegisterOnGlobalMapper() => Register(global::LiteDB.BsonMapper.Global);");
        writer.BlankLine();

        WriteReadHelpers(writer, needsUtcStorage);

        if (needsDtoDocument)
        {
            WriteDateTimeOffsetHelpers(writer);
        }

        for (var index = 0; index < models.Length; index++)
        {
            var model = models[index];
            var (_, parseLines, parseType) = GetLiteDbExpressions(model);
            var fq = model.FullyQualifiedTypeName;
            writer.BlankLine();
            writer.WriteLine($"private static {parseType} Parse{index}(global::LiteDB.BsonValue bson)");
            writer.OpenBrace();
            writer.WriteLine("try");
            writer.OpenBrace();
            foreach (var line in parseLines)
            {
                writer.WriteLine(line);
            }

            writer.CloseBrace();
            writer.WriteLine("catch (global::System.Exception ex) when (ex is not global::System.FormatException)");
            writer.OpenBrace();
            writer.WriteLine($"throw MalformedValue<{fq}>($\"the stored BSON value cannot be converted ({{ex.Message}}).\");");
            writer.CloseBrace();
            writer.CloseBrace();
        }

        writer.CloseBrace();
        writer.CloseBrace();
        return writer.ToString();
    }

    /// <summary>
    /// Builds the write lambda and the parse statements for one wrapper. The write lambda converts the
    /// wrapper to a BSON value; the parse statements convert a BSON value back to the wrapped (or
    /// underlying nullable) type. A wrapper around <c>Nullable&lt;T&gt;</c> stores a <c>{ "Value": bson }</c>
    /// document, because LiteDB cannot read a BSON <c>Null</c> back into a registered value-type custom
    /// mapping (the engine throws inside <c>DeserializeObject</c> before calling the mapping). The parse
    /// statements are wrapped in a try/catch by the caller, which turns any failure — including the
    /// <c>OverflowException</c> from a checked cast or the <c>ArgumentOutOfRangeException</c> from an
    /// out-of-range <c>TimeOnly</c> — into a described <see cref="FormatException"/>.
    /// </summary>
    private static (string Write, string[] ParseBody, string ParseType) GetLiteDbExpressions(PrimifyModel model)
    {
        var fq = model.FullyQualifiedTypeName;
        var wrapsNullable = model.WrapsNullableValueType;
        var wv = wrapsNullable ? "wrapper.Value.GetValueOrDefault()" : "wrapper.Value";
        var ut = model.UnderlyingWrappedType;
        var parseType = model.WrappedTypeQualified!;

        string writeValue = model.LiteDbStorage switch
        {
            LiteDbStorageKind.String =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Boolean =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Int32 =>
                $"new global::LiteDB.BsonValue((int){wv})",
            LiteDbStorageKind.Int64 =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.UInt32 =>
                $"new global::LiteDB.BsonValue((long){wv})",
            LiteDbStorageKind.UInt64 =>
                $"new global::LiteDB.BsonValue(checked((long){wv}))",
            LiteDbStorageKind.Double =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Single =>
                $"new global::LiteDB.BsonValue((double){wv})",
            LiteDbStorageKind.Half =>
                $"new global::LiteDB.BsonValue((double){wv})",
            LiteDbStorageKind.Decimal =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.Guid =>
                $"new global::LiteDB.BsonValue({wv})",
            LiteDbStorageKind.UtcDateTime =>
                $"new global::LiteDB.BsonValue(EnsureUtc({wv}))",
            LiteDbStorageKind.TimeSpanTicks =>
                $"new global::LiteDB.BsonValue({wv}.Ticks)",
            LiteDbStorageKind.TimeOnlyTicks =>
                $"new global::LiteDB.BsonValue({wv}.Ticks)",
            LiteDbStorageKind.DateOnlyUtcMidnight =>
                $"new global::LiteDB.BsonValue(global::System.DateTime.SpecifyKind({wv}.ToDateTime(global::System.TimeOnly.MinValue), global::System.DateTimeKind.Utc))",
            LiteDbStorageKind.DateTimeOffsetDocument =>
                $"new global::LiteDB.BsonDocument {{ [\"UtcTicks\"] = new global::LiteDB.BsonValue({wv}.UtcTicks), [\"OffsetTicks\"] = new global::LiteDB.BsonValue({wv}.Offset.Ticks) }}",
            _ => $"new global::LiteDB.BsonValue({wv})"
        };

        var write = wrapsNullable
            ? $"wrapper => new global::LiteDB.BsonDocument {{ [\"Value\"] = wrapper.Value.HasValue ? {writeValue} : global::LiteDB.BsonValue.Null }}"
            : $"wrapper => {writeValue}";

        string[] Body(string b) => model.LiteDbStorage switch
        {
            LiteDbStorageKind.String =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.String);",
                $"return {b}.AsString;"
            ],
            LiteDbStorageKind.Boolean =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Boolean);",
                $"return {b}.AsBoolean;"
            ],
            LiteDbStorageKind.Int32 =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);",
                $"return checked(({ut}){b}.AsInt64);"
            ],
            LiteDbStorageKind.Int64 =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);",
                $"return checked((long){b}.AsInt64);"
            ],
            LiteDbStorageKind.UInt32 =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);",
                $"return checked((uint){b}.AsInt64);"
            ],
            LiteDbStorageKind.UInt64 =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int64);",
                $"return checked((ulong){b}.AsInt64);"
            ],
            LiteDbStorageKind.Double =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Double);",
                $"return {b}.AsDouble;"
            ],
            LiteDbStorageKind.Single =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Double);",
                $"var single = {b}.AsDouble;",
                "if (double.IsFinite(single) && global::System.Math.Abs(single) > global::System.Single.MaxValue)",
                "{",
                $"    throw MalformedValue<{fq}>(\"the stored double is out of range for System.Single.\");",
                "}",
                "return (float)single;"
            ],
            LiteDbStorageKind.Half =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Double);",
                $"var half = {b}.AsDouble;",
                "if (double.IsFinite(half) && global::System.Math.Abs(half) > (double)global::System.Half.MaxValue)",
                "{",
                $"    throw MalformedValue<{fq}>(\"the stored double is out of range for System.Half.\");",
                "}",
                "return (global::System.Half)half;"
            ],
            LiteDbStorageKind.Decimal =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Decimal);",
                $"return {b}.AsDecimal;"
            ],
            LiteDbStorageKind.Guid =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Guid);",
                $"return {b}.AsGuid;"
            ],
            LiteDbStorageKind.UtcDateTime =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.DateTime);",
                $"return {b}.AsDateTime.ToUniversalTime();"
            ],
            LiteDbStorageKind.TimeSpanTicks =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);",
                $"return new global::System.TimeSpan({b}.AsInt64);"
            ],
            LiteDbStorageKind.TimeOnlyTicks =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.Int32, global::LiteDB.BsonType.Int64);",
                $"return new global::System.TimeOnly({b}.AsInt64);"
            ],
            LiteDbStorageKind.DateOnlyUtcMidnight =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.DateTime);",
                $"return global::System.DateOnly.FromDateTime({b}.AsDateTime.ToUniversalTime());"
            ],
            LiteDbStorageKind.DateTimeOffsetDocument =>
            [
                $"return ReadDateTimeOffsetDocument<{fq}>({b});"
            ],
            _ =>
            [
                $"Expect<{fq}>({b}, global::LiteDB.BsonType.String);",
                $"return {b}.AsString;"
            ]
        };

        string[] parseLines = wrapsNullable
            ?
            [
                "if (bson is null || bson is not global::LiteDB.BsonDocument document)",
                "{",
                $"    throw MalformedValue<{fq}>(bson is null",
                "        ? \"expected a '{ Value }' document but found null.\"",
                "        : $\"expected a '{{ Value }}' document but found {bson.Type}.\");",
                "}",
                "if (!document.TryGetValue(\"Value\", out var value))",
                "{",
                $"    throw MalformedValue<{fq}>(\"the document is missing the 'Value' field.\");",
                "}",
                "if (value.IsNull)",
                "{",
                "    return default;",
                "}",
                .. Body("value")
            ]
            : Body("bson");

        return (write, parseLines, parseType);
    }

    private static void WriteReadHelpers(SourceWriter writer, bool needsUtcStorage)
    {
        writer.WriteLine("private static void Expect<TWrapper>(global::LiteDB.BsonValue bson, global::LiteDB.BsonType expected)");
        writer.OpenBrace();
        writer.WriteLine("if (bson.Type != expected)");
        writer.OpenBrace();
        writer.WriteLine("throw new global::System.FormatException($\"Primify cannot read the stored BSON value for '{typeof(TWrapper).Name}': expected {expected} but found {bson.Type}.\");");
        writer.CloseBrace();
        writer.CloseBrace();
        writer.BlankLine();
        writer.WriteLine("private static void Expect<TWrapper>(global::LiteDB.BsonValue bson, global::LiteDB.BsonType first, global::LiteDB.BsonType second)");
        writer.OpenBrace();
        writer.WriteLine("if (bson.Type == first || bson.Type == second)");
        writer.OpenBrace();
        writer.WriteLine("return;");
        writer.CloseBrace();
        writer.WriteLine("throw new global::System.FormatException($\"Primify cannot read the stored BSON value for '{typeof(TWrapper).Name}': expected {first} or {second} but found {bson.Type}.\");");
        writer.CloseBrace();

        if (needsUtcStorage)
        {
            writer.BlankLine();
            writer.WriteLine("// Treat an Unspecified-kind DateTime as UTC instead of local time: the ticks are stored as");
            writer.WriteLine("// written, and reading them back as UTC preserves the wall clock. A Local DateTime is converted.");
            writer.WriteLine("private static global::System.DateTime EnsureUtc(global::System.DateTime value) =>");
            writer.PushIndent();
            writer.WriteLine("value.Kind == global::System.DateTimeKind.Unspecified");
            writer.WriteLine("    ? global::System.DateTime.SpecifyKind(value, global::System.DateTimeKind.Utc)");
            writer.WriteLine("    : value.ToUniversalTime();");
            writer.PopIndent();
        }

        writer.BlankLine();
        writer.WriteLine("private static global::System.FormatException MalformedValue<TWrapper>(string reason) =>");
        writer.PushIndent();
        writer.WriteLine("new($\"Primify cannot read the stored BSON value for '{typeof(TWrapper).Name}': {reason}\");");
        writer.PopIndent();
    }

    private static void WriteDateTimeOffsetHelpers(SourceWriter writer)
    {
        writer.BlankLine();
        writer.WriteLine("// LiteDB has no native DateTimeOffset type and its BSON DateTime is millisecond-precision, so both");
        writer.WriteLine("// components are stored as raw tick counts: the instant stays exact to the tick and the offset survives.");
        writer.WriteLine("private static global::System.DateTimeOffset ReadDateTimeOffsetDocument<TWrapper>(global::LiteDB.BsonValue bson)");
        writer.OpenBrace();
        writer.WriteLine("if (bson is not global::LiteDB.BsonDocument document)");
        writer.OpenBrace();
        writer.WriteLine("throw MalformedValue<TWrapper>($\"expected a '{{ UtcTicks, OffsetTicks }}' document but found {bson.Type}.\");");
        writer.CloseBrace();
        writer.BlankLine();
        writer.WriteLine("if (!TryReadTicks(document, \"UtcTicks\", out var utcTicks) ||");
        writer.WriteLine("    !TryReadTicks(document, \"OffsetTicks\", out var offsetTicks))");
        writer.OpenBrace();
        writer.WriteLine("throw MalformedValue<TWrapper>(");
        writer.PushIndent();
        writer.WriteLine("\"the document is missing integer 'UtcTicks' and 'OffsetTicks' fields.\");");
        writer.PopIndent();
        writer.CloseBrace();
        writer.BlankLine();
        writer.WriteLine("try");
        writer.OpenBrace();
        writer.WriteLine("return new global::System.DateTimeOffset(utcTicks, global::System.TimeSpan.Zero)");
        writer.WriteLine("    .ToOffset(global::System.TimeSpan.FromTicks(offsetTicks));");
        writer.CloseBrace();
        writer.WriteLine("catch (global::System.ArgumentException exception)");
        writer.OpenBrace();
        writer.WriteLine("throw MalformedValue<TWrapper>($\"the stored ticks are not a valid instant ({exception.Message}).\");");
        writer.CloseBrace();
        writer.CloseBrace();
        writer.BlankLine();
        writer.WriteLine("private static bool TryReadTicks(global::LiteDB.BsonDocument document, string field, out long ticks)");
        writer.OpenBrace();
        writer.WriteLine("ticks = 0;");
        writer.BlankLine();
        writer.WriteLine("if (!document.TryGetValue(field, out var value) || value.Type != global::LiteDB.BsonType.Int64)");
        writer.OpenBrace();
        writer.WriteLine("return false;");
        writer.CloseBrace();
        writer.BlankLine();
        writer.WriteLine("ticks = value.AsInt64;");
        writer.WriteLine("return true;");
        writer.CloseBrace();
    }

    /// <summary>
    /// Renders the Newtonsoft.Json converter emitted into the consumer compilation when Newtonsoft.Json is
    /// referenced. The BSON branches are included only when Newtonsoft.Json.Bson is referenced as well.
    /// </summary>
    public static string RenderNewtonsoftConverter(bool bsonAvailable)
    {
        var writer = new SourceWriter();
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.BlankLine();
        writer.WriteLine("namespace Primify.Converters;");
        writer.BlankLine();
        if (bsonAvailable)
        {
            writer.WriteLine("/// <summary>");
            writer.WriteLine("/// A reflection-free JSON + BSON converter for Primify wrapper types using Newtonsoft.Json, generated only");
            writer.WriteLine("/// when the consumer references Newtonsoft.Json and Newtonsoft.Json.Bson. The generator attaches it to");
            writer.WriteLine("/// every wrapper via <c>[JsonConverter(typeof(NewtonsoftJsonConverter&lt;TWrapper,TValue&gt;))]</c>.");
            writer.WriteLine("/// </summary>");
            writer.WriteLine("/// <remarks>");
            writer.WriteLine("/// Standard JSON payloads carry the bare primitive. DateTimeOffset values use");
            writer.WriteLine("/// { \"UtcTicks\": ..., \"OffsetTicks\": ... } so the original offset survives Json.NET's date tokenization.");
            writer.WriteLine("/// When writing to a <c>global::Newtonsoft.Json.Bson.BsonDataWriter</c>, the value is wrapped as { \"Value\": ... }; DateTimeOffset");
            writer.WriteLine("/// uses the same tick object inside that field. Deserialization rebuilds the wrapper through");
            writer.WriteLine("/// <see cref=\"global::Primify.IPrimify{TSelf, TValue}.From(TValue)\"/>, so invalid payloads throw the wrapper's validation");
            writer.WriteLine("/// exception instead of yielding an unvalidated instance.");
            writer.WriteLine("/// </remarks>");
        }
        else
        {
            writer.WriteLine("/// <summary>");
            writer.WriteLine("/// A reflection-free JSON converter for Primify wrapper types using Newtonsoft.Json, generated only when");
            writer.WriteLine("/// the consumer references Newtonsoft.Json. The generator attaches it to every wrapper via");
            writer.WriteLine("/// <c>[JsonConverter(typeof(NewtonsoftJsonConverter&lt;TWrapper,TValue&gt;))]</c>.");
            writer.WriteLine("/// </summary>");
            writer.WriteLine("/// <remarks>");
            writer.WriteLine("/// Reads deserialize the inner value first, then rebuild the wrapper through");
            writer.WriteLine("/// <see cref=\"global::Primify.IPrimify{TSelf, TValue}.From(TValue)\"/>, so validation runs during deserialization.");
            writer.WriteLine("/// DateTimeOffset values use { \"UtcTicks\": ..., \"OffsetTicks\": ... } so the original offset survives");
            writer.WriteLine("/// Json.NET's date tokenization.");
            writer.WriteLine("/// </remarks>");
        }

        writer.WriteLine("internal sealed class NewtonsoftJsonConverter<TWrapper, TValue> : global::Newtonsoft.Json.JsonConverter");
        writer.WriteLine("    where TWrapper : global::Primify.IPrimify<TWrapper, TValue>");
        writer.OpenBrace();
        writer.WriteLine("/// <summary>Accepts only the exact wrapper type, so the converter is never reused for a related type.</summary>");
        writer.WriteLine("public override bool CanConvert(global::System.Type objectType) => objectType == typeof(TWrapper);");
        writer.BlankLine();

        WriteNewtonsoftWriteJson(writer, bsonAvailable);
        WriteNewtonsoftReadJson(writer, bsonAvailable);

        if (bsonAvailable)
        {
            WriteNewtonsoftReadAndWrapValue(writer);
        }

        writer.BlankLine();
        WriteNewtonsoftDateTimeOffsetHelpers(writer);
        writer.CloseBrace();
        return writer.ToString();
    }

    private static void WriteNewtonsoftWriteJson(SourceWriter writer, bool bsonAvailable)
    {
        if (bsonAvailable)
        {
            writer.WriteLine("/// <summary>Writes the bare primitive, or a { \"Value\": ... } object when writing through a <c>global::Newtonsoft.Json.Bson.BsonDataWriter</c>.</summary>");
        }
        else
        {
            writer.WriteLine("/// <summary>Writes the bare primitive, or the tick object for DateTimeOffset, keeping payloads flat.</summary>");
        }

        writer.WriteLine("public override void WriteJson(global::Newtonsoft.Json.JsonWriter writer, object? value, global::Newtonsoft.Json.JsonSerializer serializer)");
        writer.OpenBrace();
        writer.WriteLine("if (value is null)");
        writer.OpenBrace();
        writer.WriteLine("writer.WriteNull();");
        writer.WriteLine("return;");
        writer.CloseBrace();
        writer.BlankLine();
        writer.WriteLine("var wrapper = (TWrapper)value;");
        writer.WriteLine("var innerValue = (object)wrapper.Value!;");
        writer.BlankLine();

        if (bsonAvailable)
        {
            writer.WriteLine("if (innerValue is global::System.DateTimeOffset dateTimeOffset && writer is not global::Newtonsoft.Json.Bson.BsonDataWriter)");
            writer.OpenBrace();
            writer.WriteLine("WriteDateTimeOffsetObject(writer, dateTimeOffset);");
            writer.CloseBrace();
            writer.WriteLine("else if (writer is global::Newtonsoft.Json.Bson.BsonDataWriter)");
            writer.OpenBrace();
            writer.WriteLine("writer.WriteStartObject();");
            writer.WriteLine("writer.WritePropertyName(\"Value\");");
            writer.WriteLine("if (innerValue is global::System.DateTimeOffset dto)");
            writer.OpenBrace();
            writer.WriteLine("WriteDateTimeOffsetObject(writer, dto);");
            writer.CloseBrace();
            writer.WriteLine("else");
            writer.OpenBrace();
            writer.WriteLine("serializer.Serialize(writer, innerValue);");
            writer.CloseBrace();
            writer.WriteLine("writer.WriteEndObject();");
            writer.CloseBrace();
            writer.WriteLine("else");
            writer.OpenBrace();
            writer.WriteLine("serializer.Serialize(writer, innerValue);");
            writer.CloseBrace();
        }
        else
        {
            writer.WriteLine("if (innerValue is global::System.DateTimeOffset dateTimeOffset)");
            writer.OpenBrace();
            writer.WriteLine("WriteDateTimeOffsetObject(writer, dateTimeOffset);");
            writer.CloseBrace();
            writer.WriteLine("else");
            writer.OpenBrace();
            writer.WriteLine("serializer.Serialize(writer, innerValue);");
            writer.CloseBrace();
        }

        writer.CloseBrace();
        writer.BlankLine();
    }

    private static void WriteNewtonsoftReadJson(SourceWriter writer, bool bsonAvailable)
    {
        if (bsonAvailable)
        {
            writer.WriteLine("/// <summary>Reads a primitive, a DateTimeOffset tick object, or a BSON { \"Value\": ... } shape and returns a validated wrapper.</summary>");
        }
        else
        {
            writer.WriteLine("/// <summary>Reads a primitive or a DateTimeOffset tick object and returns a validated wrapper.</summary>");
        }

        writer.WriteLine("public override object? ReadJson(global::Newtonsoft.Json.JsonReader reader, global::System.Type objectType, object? existingValue, global::Newtonsoft.Json.JsonSerializer serializer)");
        writer.OpenBrace();
        writer.WriteLine("if (reader.TokenType == global::Newtonsoft.Json.JsonToken.Null)");
        writer.OpenBrace();
        writer.WriteLine("return null;");
        writer.CloseBrace();

        if (bsonAvailable)
        {
            writer.BlankLine();
            writer.WriteLine("// global::Newtonsoft.Json.Bson.BsonDataReader tokenizes dates into local time before the converter sees them, so read the");
            writer.WriteLine("// tick object as UTC and restore the stored offset afterwards.");
            writer.WriteLine("if (reader is global::Newtonsoft.Json.Bson.BsonDataReader bsonReader && typeof(TValue) == typeof(global::System.DateTimeOffset))");
            writer.OpenBrace();
            writer.WriteLine("var originalKind = bsonReader.DateTimeKindHandling;");
            writer.WriteLine("try");
            writer.OpenBrace();
            writer.WriteLine("bsonReader.DateTimeKindHandling = global::System.DateTimeKind.Utc;");
            writer.WriteLine("return ReadAndWrapValue(reader, serializer);");
            writer.CloseBrace();
            writer.WriteLine("finally");
            writer.OpenBrace();
            writer.WriteLine("bsonReader.DateTimeKindHandling = originalKind;");
            writer.CloseBrace();
            writer.CloseBrace();
            writer.BlankLine();
            writer.WriteLine("return ReadAndWrapValue(reader, serializer);");
        }
        else
        {
            writer.BlankLine();
            writer.WriteLine("object? rawValue;");
            writer.BlankLine();
            writer.WriteLine("if (reader.TokenType == global::Newtonsoft.Json.JsonToken.StartObject)");
            writer.OpenBrace();
            writer.WriteLine("if (typeof(TValue) == typeof(global::System.DateTimeOffset) && reader is global::Newtonsoft.Json.JsonTextReader)");
            writer.OpenBrace();
            writer.WriteLine("rawValue = ReadDateTimeOffsetObject(reader);");
            writer.CloseBrace();
            writer.WriteLine("else");
            writer.OpenBrace();
            writer.WriteLine("throw new global::Newtonsoft.Json.JsonSerializationException(\"A Primify wrapper must be a primitive JSON value.\");");
            writer.CloseBrace();
            writer.CloseBrace();
            writer.WriteLine("else");
            writer.OpenBrace();
            writer.WriteLine("rawValue = serializer.Deserialize<TValue>(reader);");
            writer.CloseBrace();
            writer.BlankLine();
            writer.WriteLine("if (rawValue is null)");
            writer.OpenBrace();
            writer.WriteLine("throw new global::Newtonsoft.Json.JsonSerializationException($\"The JSON payload does not contain a value for {typeof(TValue).Name}.\");");
            writer.CloseBrace();
            writer.BlankLine();
            writer.WriteLine("return TWrapper.From((TValue)rawValue);");
        }

        writer.CloseBrace();
        writer.BlankLine();
    }

